import { existsSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import type { H } from '@hubble/room'
import { validTransform } from './spatial/coordinates.ts'

/**
 * Which camera → projector calibration the runtime boots with, and where it
 * came from.
 *
 * Why this exists (7 Oct): the only calibration was `.hubble/calibration.json`,
 * a gitignored file a live run writes. On 7 Oct that file was lost with a
 * deleted worktree, so the room booted uncalibrated — the projected keyboard
 * and the lit piano keys both stand on this map, so the demo ran blind.
 * Recalibrating live failed because the projector wasn't showing our page. A
 * committed calibration derived from the recorded good run means the room
 * always boots with a usable map; a fresh live run only improves on it.
 *
 * The decision (measured beats standard, standard beats nothing) lives in one
 * function, `resolveCalibration`, so a second fallback can never be added
 * somewhere else and silently disagree about which map is in use.
 */

/** How the map in use was obtained. `measured` = a live run this boot; `standard` = the committed recording. */
export type CalibrationSource = 'measured' | 'standard' | null

export interface CalibrationData {
  /** Camera px → projector/table px (the /table page's own Surface). */
  cameraToProjector: H
  cameraGeometry: { width: number; height: number }
  /** Reprojection error of the dots kept, table px; null when the saved file omitted it. */
  rms: number | null
  measuredAt: string
  /** Per dot: where it was drawn and where the camera saw it (null: not seen). */
  dots: unknown[]
  /**
   * How far the page in use was moved from the page the map was fitted on,
   * in px. Absent for a live run (it fitted the page in use) and for the old
   * 1080-page era; the committed standard carries it so a future reader can
   * see the recording's page origin was corrected.
   */
  pageOffsetPx?: { x: number; y: number }
}

export interface ResolvedCalibration {
  source: Exclude<CalibrationSource, null>
  data: CalibrationData
}

/**
 * The committed calibration: `apps/server/calibration.standard.json`, derived
 * from the recording `fixtures/calibration-2026-10-07/` and regenerated by
 * `npm run calibration:standard`. It is read from disk, not imported, so the
 * fixture-refit test and the runtime read the exact same bytes.
 */
export const STANDARD_CALIBRATION_FILE = fileURLToPath(new URL('./calibration.standard.json', import.meta.url))

/** A positive integer, the only camera dimension setCamera will accept. */
const positiveInt = (v: unknown): v is number => typeof v === 'number' && Number.isInteger(v) && v > 0

/**
 * Read one calibration file into the shape the runtime uses, or null if it is
 * missing, unparseable, or not a valid registration. "Valid" means both the
 * homography (a singular or NaN map is refused here, not installed to make
 * NaN key corners later) and the camera geometry. The legacy file may omit
 * geometry, in which case the full-frame 1080p default stands; but when it is
 * present, width and height must be positive integers — a 0, negative or
 * fractional size throws out of setCamera at boot, which is exactly the crash
 * a corrupt cache must never cause (Codex review, finding 2).
 */
export function readCalibrationFile(file: string): CalibrationData | null {
  if (!existsSync(file)) return null
  try {
    const raw = JSON.parse(readFileSync(file, 'utf8')) as Partial<CalibrationData>
    if (!Array.isArray(raw.cameraToProjector) || !validTransform(raw.cameraToProjector)) return null
    if (raw.cameraGeometry !== undefined && (!positiveInt(raw.cameraGeometry.width) || !positiveInt(raw.cameraGeometry.height))) return null
    return {
      cameraToProjector: raw.cameraToProjector,
      cameraGeometry: {
        width: positiveInt(raw.cameraGeometry?.width) ? raw.cameraGeometry.width : 1920,
        height: positiveInt(raw.cameraGeometry?.height) ? raw.cameraGeometry.height : 1080,
      },
      rms: typeof raw.rms === 'number' && Number.isFinite(raw.rms) ? raw.rms : null,
      measuredAt: typeof raw.measuredAt === 'string' ? raw.measuredAt : '',
      dots: Array.isArray(raw.dots) ? raw.dots : [],
      pageOffsetPx: raw.pageOffsetPx && Number.isFinite(raw.pageOffsetPx.x) && Number.isFinite(raw.pageOffsetPx.y) ? raw.pageOffsetPx : undefined,
    }
  } catch {
    // A truncated or corrupted file is the same as a missing one: fall through
    // to the standard. Never throw out of boot over a bad cache.
    return null
  }
}

/**
 * The one owner of "which calibration is in use". A valid measured file wins
 * (a live run knows today's room better than a recording); otherwise the
 * committed standard; otherwise nothing, and the runtime stays uncalibrated.
 */
export function resolveCalibration(measuredFile: string): ResolvedCalibration | null {
  const measured = readCalibrationFile(measuredFile)
  if (measured) return { source: 'measured', data: measured }
  const standard = readCalibrationFile(STANDARD_CALIBRATION_FILE)
  return standard ? { source: 'standard', data: standard } : null
}
