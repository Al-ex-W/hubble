import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Regenerates src/swipe/lexicon-words.ts from src/swipe/lexicon.txt.
 *
 * Why a generated module and not the .txt itself: the swipe keyboard's rules
 * run in the browser (Vite) AND on the server (tsx, #29: the runtime owns
 * what is typed on the projected keyboard). Vite can import a text file with
 * `?raw`; tsx can't, and reading it with `fs` would break the browser. A .ts
 * module works in both. The .txt stays the source of truth (it is the
 * upstream list, diffable word by word); lexicon.test.ts fails if the two
 * ever disagree, so editing one without running this can't slip through.
 *
 * Run: npx tsx packages/stage/scripts/gen-lexicon.ts
 */
const dir = join(import.meta.dirname, '../src/swipe')
const words = readFileSync(join(dir, 'lexicon.txt'), 'utf8')
writeFileSync(
  join(dir, 'lexicon-words.ts'),
  `// GENERATED by scripts/gen-lexicon.ts from lexicon.txt. Do not edit; edit the .txt and re-run.\nexport const LEXICON_TXT = ${JSON.stringify(words)}\n`,
)
