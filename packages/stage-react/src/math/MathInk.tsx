import { useEffect, useMemo, useState, type CSSProperties } from 'react'
import { typeset } from './typeset.ts'

/**
 * Draw a complete LaTeX string as if a pen were writing it.
 *
 * MathJax returns each glyph as a filled <path>. We repurpose those paths as
 * *strokes*: `pathLength="1"` normalises every path to length 1 so a single
 * dash-array keyframe draws any glyph, with no per-path measurement. The fill
 * then fades in behind the stroke, which is what ink doing into paper looks
 * like. This also means the animation is generated purely from the SVG string,
 * so it is deterministic and testable without a DOM.
 */

const STYLE_ELEMENT_ID = 'mathink-keyframes'

/**
 * Injected once per document. Using a real stylesheet (rather than per-path
 * @keyframes) keeps multiple Math pieces on a table from duplicating rules and
 * lets the browser share the animation timeline across all glyphs.
 */
function ensureKeyframes(): void {
  if (typeof document === 'undefined' || document.getElementById(STYLE_ELEMENT_ID)) return
  const style = document.createElement('style')
  style.id = STYLE_ELEMENT_ID
  style.textContent = `
@keyframes mathink-draw {
  from { stroke-dashoffset: 1; }
  to   { stroke-dashoffset: 0; }
}
@keyframes mathink-fill {
  from { fill-opacity: 0; }
  to   { fill-opacity: 1; }
}
@keyframes mathink-bar {
  to { transform: scaleX(1); }
}
@keyframes mathink-appear {
  from { opacity: 0; }
  to   { opacity: 1; }
}
.mathink-svg { color: currentColor; overflow: visible; }
.mathink-svg.mathink-highlight { filter: drop-shadow(0 0 0.18em #6cf0ff) drop-shadow(0 0 0.42em rgba(108, 240, 255, 0.65)); }
.mathink-fallback { font: inherit; font-family: ui-monospace, SFMono-Regular, Menlo, monospace; white-space: pre-wrap; animation: mathink-appear 600ms ease forwards; }
`
  document.head.appendChild(style)
}

/**
 * Gives every drawn element its pen animation. Glyphs are <path>s; fraction
 * bars and roots' overlines are <rect>s, which would otherwise pop in whole
 * while the glyphs around them are still being written.
 */
function animateSvg(svg: string, glyphs: number, duration: number): string {
  const marks = svg.match(/<(path|rect)\b/g)?.length ?? glyphs
  const perMark = (duration * 0.75) / Math.max(marks, 1)
  const drawMs = Math.min(duration * 0.35, 450)
  const fillMs = drawMs * 0.4
  const fillStart = drawMs * 0.6

  let index = 0
  return svg.replace(/<(path|rect)\b/g, (_m, tag: string) => {
    const delay = index * perMark
    index += 1
    if (tag === 'rect') {
      // A bar is drawn left to right, like a pen stroke across the fraction.
      return `<rect style="transform-box:fill-box;transform-origin:left center;transform:scaleX(0);animation:mathink-bar ${drawMs}ms ease-out ${delay}ms forwards" `
    }
    const style = [
      'stroke-dasharray:1',
      'stroke-dashoffset:1',
      'fill-opacity:0',
      'stroke:currentColor',
      'stroke-width:24',
      'stroke-linecap:round',
      'stroke-linejoin:round',
      `animation:mathink-draw ${drawMs}ms linear ${delay}ms forwards, mathink-fill ${fillMs}ms ease-out ${delay + fillStart}ms forwards`,
    ].join(';')
    return `<path pathLength="1" style="${style}" `
  })
}

export function MathInk(props: { tex: string; duration: number; highlight?: boolean }): JSX.Element {
  const { tex, duration, highlight } = props

  useEffect(() => {
    ensureKeyframes()
  }, [])

  const result = useMemo(() => typeset(tex), [tex])
  const [finished, setFinished] = useState(false)

  // The glow is a state after the pen stops, not a concurrent animation, so it
  // never competes with the glyph animations for the compositor.
  useEffect(() => {
    if (!highlight) return
    setFinished(false)
    const timer = setTimeout(() => setFinished(true), Math.max(duration, 0))
    return () => clearTimeout(timer)
  }, [highlight, duration, tex])

  // StageView no longer re-renders every frame (the reveal clock ticks only
  // when something is due, #17), but it still re-renders on every reveal and
  // every measured panel height. Animating the SVG is string surgery over the
  // whole typeset glyph set, so it is done once per (svg, duration), not once
  // per render: on the table's Raspberry Pi that work is what stutters.
  const html = useMemo(() => (result.ok ? animateSvg(result.svg, result.glyphs, duration) : ''), [result, duration])

  if (!result.ok) {
    // A failed typeset must never throw or blank the table: show the TeX source
    // in monospace so the failure is visible rather than silent.
    return <span className="mathink-fallback">{tex}</span>
  }

  const className = `mathink-svg${highlight && finished ? ' mathink-highlight' : ''}`

  const wrapperStyle: CSSProperties = { display: 'inline-block', lineHeight: 0 }

  return (
    <span style={wrapperStyle}>
      {/* MathJax output is generated by our own typeset(), not model text. */}
      <span className={className} style={{ display: 'inline-block', lineHeight: 0 }} dangerouslySetInnerHTML={{ __html: html }} />
    </span>
  )
}
